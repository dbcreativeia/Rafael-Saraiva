// Decodes double-encoded UTF-8 strings (mojibake) commonly introduced during CSV / Excel imports
export function fixMojibake(str?: string | null): string {
  if (!str) return '';
  return str
    .replace(/Ã£|ã£/g, 'ã')
    .replace(/Ã§|ã§/g, 'ç')
    .replace(/Ã¡|ã¡/g, 'á')
    .replace(/Ã©|ã©/g, 'é')
    .replace(/Ã­|ã­/g, 'í')
    .replace(/Ã³/g, 'ó')
    .replace(/ã³/g, 'ó')
    .replace(/Ãº|ãº/g, 'ú')
    .replace(/Ã¢|ã¢/g, 'â')
    .replace(/Ãª|ãª/g, 'ê')
    .replace(/Ã´|ã´/g, 'ô')
    .replace(/Ãµ|ãµ/g, 'õ')
    .replace(/Ã€|ã€/g, 'À')
    .replace(/Ã\x81/g, 'Á')
    .replace(/Ã/g, 'Á')
    .replace(/â€™/g, "'")
    .replace(/â€“/g, "-")
    .replace(/â€œ/g, '"')
    .replace(/â€/g, '"');
}

// Checks if a city name is strictly one of the 645 official IBGE municipalities of São Paulo state
export const isSpCity = (cityName?: string | null): boolean => {
  if (!cityName) return false;
  const fixed = fixMojibake(cityName);
  const norm = fixed.trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9\s]/gi, ' ').replace(/\s+/g, ' ').trim();
  const cleanKey = norm.replace(/\s+/g, '');
  return spCitiesCleanMap.has(cleanKey) || spCitiesNormMap.has(norm);
};

